function enrichMenuItem(item) {
  const originalKey = `${item.cat}|${item.name}`;
  const name = MENU_NAME_FIXES[originalKey] || item.name;
  return { ...item, name, ingredients: MENU_DESCRIPTIONS[originalKey] || '' };
}

